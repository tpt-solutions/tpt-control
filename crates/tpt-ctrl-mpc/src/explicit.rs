//! Explicit MPC via precomputed lookup tables.
//!
//! True multi-parametric QP solutions partition the state space into
//! critical regions with piecewise-affine control laws. This module takes
//! the pragmatic embedding route (adequate for ultra-low-latency targets
//! where a QP solve is too slow but flash/RAM is available):
//!
//! 1. **Offline:** sample the state box on a grid, solve the online MPC at
//!    every node, and store `(state node, first move)`.
//! 2. **Online:** nearest-neighbour lookup (`O(N_nodes)` scan, or `O(log)`
//!    with a spatial index) — no matrix products, no solver.
//!
//! The trade-off versus a critical-region (mpc-MP) solution is accuracy:
//! the law is piecewise-*constant* between nodes instead of affine. Where
//! that error matters, [`ExplicitMpc::refine`] runs the exact online solve
//! at the query state instead of the table lookup.

use std::vec::Vec;

use tpt_ctrl_core::dmat::DMat;

use crate::mpc::Mpc;

/// A precomputed explicit-MPC table.
#[derive(Clone, Debug)]
pub struct ExplicitMpc {
    /// Flattened grid nodes (`n` floats per node, row-major).
    nodes: Vec<f64>,
    /// First control move at each node (`m` floats per node).
    controls: Vec<f64>,
    /// Grid bounds per state dimension: `(min, max, samples)`.
    grid: Vec<(f64, f64, usize)>,
    n: usize,
    m: usize,
}

/// Errors from explicit-MPC evaluation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ExplicitError {
    /// The queried state lies outside the sampled box.
    OutsideDomain,
    /// The state dimension does not match the table.
    DimensionMismatch,
}

impl ExplicitMpc {
    /// Builds a table by solving the MPC at every grid node.
    ///
    /// `grid` describes the sampling per state dimension; `steps` beyond
    /// the last sample are clamped during evaluation.
    pub fn build(mpc: &Mpc, grid: &[(f64, f64, usize)]) -> Result<ExplicitMpc, ExplicitError> {
        let n = mpc.n_states();
        let m = mpc.n_inputs();
        if grid.len() != n {
            return Err(ExplicitError::DimensionMismatch);
        }
        let total: usize = grid.iter().map(|(_, _, s)| s).product();
        let mut nodes = Vec::with_capacity(total * n);
        let mut controls = Vec::with_capacity(total * m);

        let mut index = vec![0usize; n];
        for _ in 0..total {
            let mut x = DMat::zeros(n, 1);
            for (i, idx) in index.iter().enumerate() {
                let (lo, hi, samples) = grid[i];
                let frac = if samples <= 1 {
                    0.5
                } else {
                    *idx as f64 / (samples - 1) as f64
                };
                x[(i, 0)] = lo + (hi - lo) * frac;
            }
            if let Ok(sol) = mpc.solve(&x) {
                nodes.extend_from_slice(&x.as_slice()[..n]);
                controls.extend_from_slice(&sol.u0);
            } else {
                // Infeasible node (e.g. state constraint unreachable):
                // store NaNs so evaluation can reject the neighbourhood.
                for _ in 0..n {
                    nodes.push(f64::NAN);
                }
                for _ in 0..m {
                    controls.push(f64::NAN);
                }
            }
            // odometer increment
            for i in (0..n).rev() {
                index[i] += 1;
                if index[i] < grid[i].2 {
                    break;
                }
                index[i] = 0;
            }
        }
        Ok(ExplicitMpc {
            nodes,
            controls,
            grid: grid.to_vec(),
            n,
            m,
        })
    }

    /// Number of stored nodes (including any infeasible markers).
    pub fn node_count(&self) -> usize {
        self.nodes.len() / self.n
    }

    /// Emits a self-contained C header: the node and control tables as
    /// `static const double` arrays, plus `<name>_lookup(x, u)` returning `0`
    /// on success and `-1` for an infeasible neighbourhood. Infeasible nodes
    /// are emitted as `NAN`. Needs only `<math.h>`.
    pub fn to_c_header(&self, name: &str) -> String {
        let up = name.to_ascii_uppercase();
        let mut out = String::new();
        out.push_str(
            "/* Generated by tpt-control ExplicitMpc::to_c_header. Do not edit. */
",
        );
        out.push_str(&format!(
            "#ifndef {up}_EXPLICIT_MPC_H
#define {up}_EXPLICIT_MPC_H

"
        ));
        out.push_str(
            "#include <math.h>

",
        );
        out.push_str(&format!(
            "#define {up}_N_STATES {}
",
            self.n
        ));
        out.push_str(&format!(
            "#define {up}_N_INPUTS {}
",
            self.m
        ));
        out.push_str(&format!(
            "#define {up}_N_NODES {}

",
            self.node_count()
        ));
        out.push_str(&format!(
            "static const double {up}_LO[{up}_N_STATES] = {{ {} }};
",
            self.bounds_list(true)
        ));
        out.push_str(&format!(
            "static const double {up}_HI[{up}_N_STATES] = {{ {} }};
",
            self.bounds_list(false)
        ));
        out.push_str(&format!(
            "static const double {up}_NODES[{up}_N_NODES * {up}_N_STATES] = {{
    {}
}};
",
            join_values(&self.nodes, true)
        ));
        out.push_str(&format!(
            "static const double {up}_CONTROLS[{up}_N_NODES * {up}_N_INPUTS] = {{
    {}
}};

",
            join_values(&self.controls, true)
        ));
        let low = name.to_ascii_lowercase();
        out.push_str(&format!(
            "/* Nearest-neighbour lookup (Euclidean), clamped to the table box. */
static inline int {low}_lookup(const double x[{up}_N_STATES], double u[{up}_N_INPUTS]) {{
    double best = INFINITY;
    int best_k = -1;
    for (int k = 0; k < {up}_N_NODES; k++) {{
        double d = 0.0;
        for (int i = 0; i < {up}_N_STATES; i++) {{
            double q = x[i];
            if (q < {up}_LO[i]) q = {up}_LO[i];
            if (q > {up}_HI[i]) q = {up}_HI[i];
            double diff = {up}_NODES[k * {up}_N_STATES + i] - q;
            d += diff * diff;
        }}
        if (d < best) {{ best = d; best_k = k; }}
    }}
    if (best_k < 0) return -1;
    for (int j = 0; j < {up}_N_INPUTS; j++) {{
        double v = {up}_CONTROLS[best_k * {up}_N_INPUTS + j];
        if (isnan(v)) return -1;
        u[j] = v;
    }}
    return 0;
}}

#endif
"
        ));
        out
    }

    /// Emits the same tables and lookup as a Rust source file (`no_std`
    /// compatible, uses `core` only), for `include!` or copy-paste into firmware.
    pub fn to_rust_source(&self, name: &str) -> String {
        let up = name.to_ascii_uppercase();
        let low = name.to_ascii_lowercase();
        let mut out = String::new();
        out.push_str(
            "// Generated by tpt-control ExplicitMpc::to_rust_source. Do not edit.

",
        );
        out.push_str(&format!(
            "pub const {up}_N_STATES: usize = {};
",
            self.n
        ));
        out.push_str(&format!(
            "pub const {up}_N_INPUTS: usize = {};
",
            self.m
        ));
        out.push_str(&format!(
            "pub const {up}_N_NODES: usize = {};

",
            self.node_count()
        ));
        out.push_str(&format!(
            "pub static {up}_LO: [f64; {up}_N_STATES] = [{}];
",
            self.bounds_list(true)
        ));
        out.push_str(&format!(
            "pub static {up}_HI: [f64; {up}_N_STATES] = [{}];
",
            self.bounds_list(false)
        ));
        out.push_str(&format!(
            "pub static {up}_NODES: [f64; {up}_N_NODES * {up}_N_STATES] = [
    {}
];
",
            join_values(&self.nodes, false)
        ));
        out.push_str(&format!(
            "pub static {up}_CONTROLS: [f64; {up}_N_NODES * {up}_N_INPUTS] = [
    {}
];

",
            join_values(&self.controls, false)
        ));
        out.push_str(&format!(
            "/// Nearest-neighbour lookup, clamped to the table box. Returns `false`
/// when the neighbourhood is infeasible.
pub fn {low}_lookup(x: &[f64; {up}_N_STATES], u: &mut [f64; {up}_N_INPUTS]) -> bool {{
    let mut best = f64::INFINITY;
    let mut best_k = usize::MAX;
    for k in 0..{up}_N_NODES {{
        let mut d = 0.0;
        for i in 0..{up}_N_STATES {{
            let q = x[i].clamp({up}_LO[i], {up}_HI[i]);
            let diff = {up}_NODES[k * {up}_N_STATES + i] - q;
            d += diff * diff;
        }}
        if d < best {{ best = d; best_k = k; }}
    }}
    if best_k == usize::MAX {{ return false; }}
    for j in 0..{up}_N_INPUTS {{
        let v = {up}_CONTROLS[best_k * {up}_N_INPUTS + j];
        if v.is_nan() {{ return false; }}
        u[j] = v;
    }}
    true
}}
"
        ));
        out
    }

    /// Per-dimension bounds as a comma-separated list (`lower` picks `lo`, else `hi`).
    fn bounds_list(&self, lower: bool) -> String {
        self.grid
            .iter()
            .map(|(lo, hi, _)| format!("{:?}", if lower { *lo } else { *hi }))
            .collect::<Vec<_>>()
            .join(", ")
    }

    /// Exact fallback: solves the online MPC QP at `x` and returns the first
    /// move. Costs one active-set solve, so use it only where the table's
    /// piecewise-constant error matters more than latency. States that the
    /// solver rejects as infeasible map to [`ExplicitError::OutsideDomain`].
    pub fn refine(mpc: &Mpc, x: &[f64]) -> Result<Vec<f64>, ExplicitError> {
        if x.len() != mpc.n_states() {
            return Err(ExplicitError::DimensionMismatch);
        }
        let mut x0 = DMat::zeros(x.len(), 1);
        for (i, v) in x.iter().enumerate() {
            x0[(i, 0)] = *v;
        }
        mpc.solve(&x0)
            .map(|sol| sol.u0)
            .map_err(|_| ExplicitError::OutsideDomain)
    }

    /// Nearest-neighbour control for state `x` (Euclidean distance).
    pub fn lookup(&self, x: &[f64]) -> Result<Vec<f64>, ExplicitError> {
        if x.len() != self.n {
            return Err(ExplicitError::DimensionMismatch);
        }
        // Clamp to the sampled box.
        let mut q = vec![0.0; self.n];
        for (i, v) in x.iter().enumerate() {
            let (lo, hi, _) = self.grid[i];
            q[i] = v.clamp(lo, hi);
        }
        let mut best = usize::MAX;
        let mut best_d = f64::INFINITY;
        for k in 0..self.node_count() {
            let mut d = 0.0;
            for (i, qi) in q.iter().enumerate() {
                let diff = self.nodes[k * self.n + i] - qi;
                d += diff * diff;
            }
            if d < best_d {
                best_d = d;
                best = k;
            }
        }
        if best == usize::MAX {
            return Err(ExplicitError::OutsideDomain);
        }
        let ctrl = &self.controls[best * self.m..(best + 1) * self.m];
        if ctrl.iter().any(|v| v.is_nan()) {
            return Err(ExplicitError::OutsideDomain);
        }
        Ok(ctrl.to_vec())
    }
}

/// Formats a table as comma-separated literals, `NAN` for infeasible nodes in
/// C mode and `f64::NAN` in Rust mode.
fn join_values(values: &[f64], c_style: bool) -> String {
    values
        .iter()
        .map(|v| {
            if v.is_nan() {
                if c_style {
                    "NAN".to_string()
                } else {
                    "f64::NAN".to_string()
                }
            } else {
                format!("{v:?}")
            }
        })
        .collect::<Vec<_>>()
        .join(", ")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::mpc::MpcBuilder;
    use tpt_ctrl_verify::testing::assert_close;

    #[test]
    fn table_agrees_with_online_solve_at_nodes() {
        let a = DMat::from_rows(&[&[1.0, 0.1], &[0.0, 1.0]]);
        let b = DMat::from_rows(&[&[0.005], &[0.1]]);
        let mpc = MpcBuilder::new(a, b, 12)
            .stage_costs(&DMat::identity(2), &DMat::from_rows(&[&[0.5]]))
            .terminal_cost(&(DMat::identity(2) * 5.0))
            .input_bounds(vec![-0.5], vec![0.5])
            .build();
        let grid = [(-2.0, 2.0, 9), (-1.0, 1.0, 7)];
        let table = ExplicitMpc::build(&mpc, &grid).unwrap();
        assert_eq!(table.node_count(), 63);

        // At grid nodes the nearest neighbour IS the node: exact match.
        for px in [-2.0, 0.0, 2.0] {
            for vx in [-1.0, 1.0] {
                let online = mpc.solve(&DMat::from_rows(&[&[px], &[vx]])).unwrap();
                let explicit = table.lookup(&[px, vx]).unwrap();
                assert_close(explicit[0], online.u0[0], 1e-9);
            }
        }
    }

    #[test]
    fn refine_matches_online_solve_off_grid() {
        let a = DMat::from_rows(&[&[1.0, 0.1], &[0.0, 1.0]]);
        let b = DMat::from_rows(&[&[0.005], &[0.1]]);
        let mpc = MpcBuilder::new(a, b, 12)
            .stage_costs(&DMat::identity(2), &DMat::from_rows(&[&[0.5]]))
            .terminal_cost(&(DMat::identity(2) * 5.0))
            .input_bounds(vec![-0.5], vec![0.5])
            .build();
        // (0.37, -0.22) is between grid nodes, so lookup is only approximate.
        let refined = ExplicitMpc::refine(&mpc, &[0.37, -0.22]).unwrap();
        let online = mpc.solve(&DMat::from_rows(&[&[0.37], &[-0.22]])).unwrap();
        assert_close(refined[0], online.u0[0], 1e-12);
    }

    #[test]
    fn refine_rejects_dimension_mismatch() {
        let a = DMat::from_rows(&[&[0.9]]);
        let b = DMat::from_rows(&[&[1.0]]);
        let mpc = MpcBuilder::new(a, b, 4)
            .stage_costs(&DMat::from_rows(&[&[1.0]]), &DMat::from_rows(&[&[1.0]]))
            .input_bounds(vec![-2.0], vec![2.0])
            .build();
        assert_eq!(
            ExplicitMpc::refine(&mpc, &[0.0, 0.0]),
            Err(ExplicitError::DimensionMismatch)
        );
    }

    fn sample_table() -> ExplicitMpc {
        let a = DMat::from_rows(&[&[0.9]]);
        let b = DMat::from_rows(&[&[1.0]]);
        let mpc = MpcBuilder::new(a, b, 8)
            .stage_costs(&DMat::from_rows(&[&[1.0]]), &DMat::from_rows(&[&[1.0]]))
            .input_bounds(vec![-2.0], vec![2.0])
            .build();
        ExplicitMpc::build(&mpc, &[(-1.0, 1.0, 5)]).unwrap()
    }

    #[test]
    fn c_header_contains_dimensions_and_tables() {
        let t = sample_table();
        let h = t.to_c_header("pendulum");
        assert!(h.contains("#define PENDULUM_N_STATES 1"));
        assert!(h.contains("#define PENDULUM_N_INPUTS 1"));
        assert!(h.contains("#define PENDULUM_N_NODES 5"));
        assert!(
            h.contains("static const double PENDULUM_NODES[PENDULUM_N_NODES * PENDULUM_N_STATES]")
        );
        assert!(h.contains("static inline int pendulum_lookup("));
        assert!(h.contains("#ifndef PENDULUM_EXPLICIT_MPC_H"));
        assert!(h.trim_end().ends_with("#endif"));
    }

    #[test]
    fn rust_source_contains_tables_and_lookup() {
        let t = sample_table();
        let src = t.to_rust_source("pendulum");
        assert!(src.contains("pub const PENDULUM_N_NODES: usize = 5;"));
        assert!(src
            .contains("pub static PENDULUM_CONTROLS: [f64; PENDULUM_N_NODES * PENDULUM_N_INPUTS]"));
        assert!(src.contains("pub fn pendulum_lookup(x: &[f64; PENDULUM_N_STATES]"));
    }

    #[test]
    fn exported_values_round_trip_through_formatting() {
        // Every node value must appear verbatim (Debug formatting is shortest
        // round-trip), so the emitted table is exactly the in-memory table.
        let t = sample_table();
        let src = t.to_rust_source("p");
        for v in &t.controls {
            assert!(src.contains(&format!("{v:?}")), "missing {v:?}");
        }
    }

    #[test]
    fn lookup_clamps_outside_domain() {
        let a = DMat::from_rows(&[&[0.9]]);
        let b = DMat::from_rows(&[&[1.0]]);
        let mpc = MpcBuilder::new(a, b, 8)
            .stage_costs(&DMat::from_rows(&[&[1.0]]), &DMat::from_rows(&[&[1.0]]))
            .input_bounds(vec![-2.0], vec![2.0])
            .build();
        let table = ExplicitMpc::build(&mpc, &[(-1.0, 1.0, 5)]).unwrap();
        // Beyond the box clamps to the edge node (symmetric system: control
        // at +edge is the mirror of -edge).
        let c = table.lookup(&[100.0]).unwrap();
        assert!(c[0].is_finite());
    }
}
